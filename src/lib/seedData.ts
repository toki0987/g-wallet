export function getCountryConfig(code: string): CountryCurrencyConfig {
  return SUPPORTED_COUNTRIES.find((c) => c.code === code) || SUPPORTED_COUNTRIES[0];
}

export function formatMoneyFromUsd(amountUsd: number, country: CountryCurrencyConfig): string {
  const localVal = amountUsd * country.rateFromUsd;
  const formatted = localVal.toLocaleString(undefined, {
    minimumFractionDigits: country.currencyCode === 'BDT' || country.currencyCode === 'INR' ? 0 : 2,
    maximumFractionDigits: country.currencyCode === 'BDT' || country.currencyCode === 'INR' ? 0 : 2,
  });
  return `${country.symbol}${formatted} ${country.currencyCode}`;
}

